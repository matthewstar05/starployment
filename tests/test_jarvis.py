def test_busy_machine_defers_scan_and_applications(running, monkeypatch):
    save([job(30, 90)])
    monkeypatch.setattr(jarvis, "_deferred", {})
    monkeypatch.setattr(governor, "busy", lambda: True)
    monkeypatch.setattr(prepare, "prepare_job", lambda *a: pytest.fail("busy Mac started preparation"))
    assert scheduler.auto_apply_batch() == []
    assert scheduler.scan_once()["status"] == "deferred"
    assert not scheduler.STATE.running_scan


def test_a_busy_machine_delays_jarvis_but_never_stops_it(monkeypatch):
    monkeypatch.setattr(governor, "busy", lambda: True)
    monkeypatch.setattr(jarvis, "_deferred", {})
    clock = [1000.0]
    monkeypatch.setattr(jarvis.time, "monotonic", lambda: clock[0])
    assert jarvis.hold("scan")
    clock[0] += jarvis.MAX_DEFER_SECONDS + 1
    assert not jarvis.hold("scan")          # waited long enough: go ahead at halved concurrency
    assert jarvis.hold("apply")             # each kind of work has its own clock
    monkeypatch.setattr(governor, "busy", lambda: False)
    assert not jarvis.hold("scan") and "scan" not in jarvis._deferred


