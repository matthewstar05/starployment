def save(jobs):
    db.upsert_jobs(jobs)
    db.update_scores({j.id: (j.score, j.score_json) for j in jobs})


def test_all_autofills_and_sends_through_durable_boundary_without_sharing_answers(running, monkeypatch):
    from jobhub import luna
    rows = [job(10, 90), job(11, 89, starred=True), job(12, 88)]
    rows[2].company = "Google"
    save(rows)
    db.set_job_star(rows[1].id, True)
    # Real question ids are generated by _question, so use the supplied id.
    def fill(job, profile, settings, questions):
        return {q["id"]: {"answer": "Application-only draft", "note": "Assumption: interest"} for q in questions}
    monkeypatch.setattr(luna, "autofill_answers", fill)
    seen = []
    def engine(job, profile, settings, resume, **kwargs):
        assert settings["show_browser"] is False
        assert settings["answers"]["approved_answers"]["Why this role?"] == "Application-only draft"
        with db.conn() as c:
            app_id = c.execute("SELECT id FROM applications WHERE job_id=?", (job.id,)).fetchone()["id"]
        db.mark_submission_attempted(job.id)
        assert db.get_application(app_id)["submission_attempted"]
        seen.append(job.id)
        return ApplyResult(status="applied", submission_attempted=True, message="Employer confirmed")
    monkeypatch.setattr(scheduler, "apply_to_job", engine)
    original_answers = db.get_settings()["answers"]
    results = scheduler.auto_apply_batch()
    assert len(results) == 1 and results[0]["status"] == "applied"
    assert seen == [rows[0].id]
    draft = db.draft_for_job(rows[0].id)
    assert draft["status"] == "sent"
    assert draft["questions"][0]["source"] == "autofill"
    assert db.get_settings()["answers"] == original_answers
    assert scheduler.auto_apply_batch() == []  # submission is never retried


