def test_policy_halves_limits_without_changing_preferences():
    settings = config.merge_settings(config.DEFAULT_SETTINGS, {"jarvis_mode": "all", "parallel_sends": 5})
    assert jarvis.parallel(settings, "parallel_sends", 4) == 2
    assert jarvis.parallel(settings, "parallel_prepare", 8) == 4
    assert jarvis.parallel(settings, "parallel_agent_calls", 4) == 2
    assert jarvis.parallel(settings, "anything", 1) == 1
    assert jarvis.interval_minutes(settings) == 30
    assert settings["parallel_sends"] == 5 and settings["scan_interval_min"] == 60
    settings["jarvis_mode"] = "off"
    assert jarvis.parallel(settings, "parallel_sends", 4) == 5
    assert jarvis.interval_minutes(settings) == 60
    with pytest.raises(ValueError):
        config.validate_settings(config.merge_settings(settings, {"jarvis_mode": "unlimited"}))


def job(number, score, age=0, **kwargs):
    date = datetime.fromtimestamp(time.time() - age * 3600, timezone.utc).isoformat()
    return Job(company=f"Example {number}", title="Data Analyst", source="greenhouse", ats="greenhouse",
               url=f"https://boards.greenhouse.io/example/jobs/{number}", description="Python SQL", score=score,
               score_json={"auto_apply_eligible": True}, posted_at=date, **kwargs)


def test_new_limits_age_and_all_balances_recency_with_match():
    recent, best, older = job(1, 60), job(2, 99, 72), job(3, 80, 48)
    assert jarvis.rank([older, best, recent], "new") == [recent]
    assert jarvis.rank([older, best, recent], "all")[:2] == [recent, best]
    assert len(jarvis.rank([older, best, recent], "all")) == 3


