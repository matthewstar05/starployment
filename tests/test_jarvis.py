def test_mode_and_star_are_rechecked_after_posting_refresh(running, monkeypatch):
    row = job(50, 90)
    save([row])
    def refresh(job):
        db.set_settings({"jarvis_mode": "off", "auto_apply": True})
        return job
    monkeypatch.setattr(scheduler, "enrich_job", refresh)
    monkeypatch.setattr(scheduler, "apply_to_job", lambda *a, **kw: pytest.fail("sent after authorization changed"))
    result = scheduler.apply_one(row.id, require_eligible=True, required_jarvis_mode="all")
    assert result["status"] == "needs_human" and not result["submission_attempted"]


def test_jarvis_global_agent_process_cap_is_halved(monkeypatch):
    lock = threading.Lock()
    counts = {"current": 0, "peak": 0}
    def complete(*args):
        with lock:
            counts["current"] += 1
            counts["peak"] = max(counts["peak"], counts["current"])
        time.sleep(0.03)
        with lock:
            counts["current"] -= 1
        return "ok"
    monkeypatch.setattr(agents, "_complete", complete)
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=12) as pool:
        assert list(pool.map(lambda _: agents.complete("fixture", {"jarvis_mode": "all"}), range(12))) == ["ok"] * 12
    assert 1 < counts["peak"] <= agents.MAX_AGENT_CALLS // 2
